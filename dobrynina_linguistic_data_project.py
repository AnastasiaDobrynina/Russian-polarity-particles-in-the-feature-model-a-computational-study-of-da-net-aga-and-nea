@torch.no_grad()
def generate_batch(rows):
    texts = [
        tokenizer.apply_chat_template(
            build_messages(r['Left context'], r['Center'], r['Punct'], r['Right context']),
            tokenize=False, add_generation_prompt=True)
        for r in rows
    ]
